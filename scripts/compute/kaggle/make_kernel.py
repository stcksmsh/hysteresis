"""Build a Kaggle kernel folder that runs one job file, ready for `kaggle kernels push -p DIR`.

    python make_kernel.py --job ../jobs/bench_b7.json --user USER --out /tmp/kern-bench \
        [--code-slug USER/hyst-code] [--data-slug USER/hyst-features ...] [--prev-kernel USER/hyst-job-b7-train-001] \
        [--no-gpu] [--no-internet] [--pip "mujoco==X jax[cuda12]==Y"]

The folder holds kernel-metadata.json and run.py. On Kaggle, run.py:
  1. finds the code dataset (HYST_DATASET.json with name hyst-code) anywhere under /kaggle/input and unpacks
     code.tar.gz into /tmp/repo (not into /kaggle/working, so code is not re-saved as output);
  2. optionally pip-installs extra packages (needs internet, i.e. a phone-verified Kaggle account);
  3. finds the data dataset (name hyst-features) the same way; its folder is passed as {DATA};
  4. if --prev-kernel was given, that kernel's saved output is attached as an input and its ckpt/ folder is passed as {PREV},
     so a job continues across Kaggle's 12 h session limit;
  5. runs scripts/compute/run_job.py with OUT=/kaggle/working/out and CKPT=/kaggle/working/ckpt (both saved as output).
Finding inputs by marker file, not by path, keeps this working if Kaggle changes its input mount layout.
To verify on first use (not checkable from here): the metadata field names below against `kaggle kernels init`,
the accelerator Kaggle assigns with enable_gpu, and the saved-output size limit.
"""
import argparse
import json
import re
import sys
from pathlib import Path

RUN_PY = r'''# generated by scripts/compute/kaggle/make_kernel.py; do not edit by hand
import glob, json, os, subprocess, sys, tarfile

JOB = {job_json}
PIP = {pip!r}
PREV_SLUG = {prev_slug!r}

def find(name):
    for marker in glob.glob("/kaggle/input/**/HYST_DATASET.json", recursive=True):
        try:
            if json.load(open(marker)).get("name") == name:
                return os.path.dirname(marker)
        except Exception:
            pass
    return None

def find_prev_ckpt():
    if not PREV_SLUG:
        return ""
    for st in glob.glob("/kaggle/input/**/out/status.json", recursive=True):
        root = os.path.dirname(os.path.dirname(st))
        if os.path.isdir(os.path.join(root, "ckpt")):
            return os.path.join(root, "ckpt")
    return ""

code = find("hyst-code")
if code is None:
    sys.exit("hyst-code dataset not attached")
repo = "/tmp/repo"
os.makedirs(repo, exist_ok=True)
with tarfile.open(os.path.join(code, "code.tar.gz")) as t:
    t.extractall(repo)
commit = open(os.path.join(code, "COMMIT")).read().strip()
JOB["commit"] = commit
if PIP:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", *PIP.split()], check=True)
data = find("hyst-features") or ""
prev = find_prev_ckpt()
job_path = "/tmp/job.json"
json.dump(JOB, open(job_path, "w"))
print("commit", commit, "data", data or "-", "prev", prev or "-", flush=True)
rc = subprocess.run([sys.executable, os.path.join(repo, "scripts/compute/run_job.py"), job_path,
                     "--repo", repo, "--out", "/kaggle/working/out", "--ckpt", "/kaggle/working/ckpt",
                     "--data", data, "--prev", prev]).returncode
print("run_job exit", rc, flush=True)
sys.exit(0)  # keep the kernel "complete" so its output (status.json, logs, ckpt) is always saved
'''

SLUG_RE = re.compile(r"^[a-z0-9-]+$")


def kernel_slug(job_id):
    s = re.sub(r"[^a-z0-9-]+", "-", ("hyst-job-" + job_id).lower()).strip("-")
    return s[:50]


def make(job_path, user, out, code_slug, data_slugs, prev_kernel=None, gpu=True, internet=True, pip=""):
    job = json.loads(Path(job_path).read_text())
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    slug = kernel_slug(job["id"])
    assert SLUG_RE.match(slug)
    meta = {
        "id": f"{user}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": bool(gpu),
        "enable_internet": bool(internet),
        "dataset_sources": [code_slug, *data_slugs],
        "kernel_sources": [prev_kernel] if prev_kernel else [],
        "competition_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    (out / "run.py").write_text(RUN_PY.format(job_json=json.dumps(job), pip=pip, prev_slug=prev_kernel or ""))
    return meta


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--job", required=True)
    ap.add_argument("--user", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--code-slug")
    ap.add_argument("--data-slug", action="append", default=[])
    ap.add_argument("--prev-kernel")
    ap.add_argument("--no-gpu", action="store_true")
    ap.add_argument("--no-internet", action="store_true")
    ap.add_argument("--pip", default="")
    a = ap.parse_args(argv)
    meta = make(a.job, a.user, a.out, a.code_slug or f"{a.user}/hyst-code", a.data_slug, a.prev_kernel,
                not a.no_gpu, not a.no_internet, a.pip)
    print(f"kernel {meta['id']} written to {a.out}; push with: kaggle kernels push -p {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
